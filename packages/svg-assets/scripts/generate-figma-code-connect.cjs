const fs = require('fs-extra');
const path = require('path');

const FIGMA_FILE_KEY = 'bZWlxN5ZzRTlDmnR1EGZun';

/**
 * The platform to generate for is derived from the --config flag, e.g.
 * `--config figma.config.react-native.json` generates the "react-native"
 * batch files, keeping the generator in sync with whichever config it's
 * pointed at rather than hardcoding platform names in two places.
 */
function parseArgs(argv) {
  const configIndex = argv.indexOf('--config');
  const configPath = configIndex !== -1 ? argv[configIndex + 1] : undefined;
  const match = configPath && path.basename(configPath).match(/^figma\.config\.(.+)\.json$/);
  if (!match) {
    throw new Error('Usage: generate-figma-code-connect.cjs --config figma.config.<platform>.json');
  }
  return { platform: match[1] };
}

/**
 * Get all assets' Figma ids & names, joined with the kebab-case file path
 * generated by generate-svg-assets.js (assets.json has id+componentSetId+name,
 * manifest.json has name+path — neither alone is enough to build a batch entry).
 */
function getAssets() {
  const assets = JSON.parse(
    fs.readFileSync(path.resolve(__dirname, '..', 'assets.json'), { encoding: 'utf8' })
  );
  const { svgAssets } = JSON.parse(
    fs.readFileSync(path.resolve(__dirname, '..', 'manifest.json'), { encoding: 'utf8' })
  );
  const pathByName = new Map(svgAssets.map(asset => [asset.name, asset.path]));

  return assets.map(asset => {
    const assetPath = pathByName.get(asset.name);
    if (!assetPath) {
      throw new Error(
        `Asset "${asset.name}" (id: ${asset.id}) is missing from manifest.json — run "pnpm generate" to regenerate it.`
      );
    }

    return {
      id: asset.id,
      // Older assets.json files predate componentSetId; fall back to the
      // variant's own id so this doesn't crash before a regenerate.
      componentSetId: asset.componentSetId || asset.id,
      name: asset.name,
      path: assetPath,
    };
  });
}

/**
 * Figma Code Connect can only attach to a top-level component or component
 * set, never to an individual Light/Dark/colour variant — so every variant
 * that shares a component set collapses into a single batch entry for that
 * set, rather than one entry per generated SVG.
 */
function groupByComponentSet(assets) {
  const groups = new Map();
  for (const asset of assets) {
    const group = groups.get(asset.componentSetId) || [];
    group.push(asset);
    groups.set(asset.componentSetId, group);
  }
  return [...groups.values()];
}

/**
 * Within a group, a real Light/Dark theme pair renders as a single
 * ThemedImage on React Native. Everything else (a lone component, or a
 * non-theme variant group like logo colour or emoji colour) renders as a
 * bare component using one representative member.
 */
function buildEntry(platform, componentSetId, members) {
  const light = members.find(m => /Light$/.test(m.name));
  const dark = members.find(m => /Dark$/.test(m.name));
  const themed = Boolean(light && dark);
  const representative = light || members[0];

  const entry = {
    url: `https://www.figma.com/design/${FIGMA_FILE_KEY}/Hearth-Illustrations---Assets?node-id=${componentSetId}&m=dev`,
    id: representative.path.replace(/\.svg$/, ''),
    name: representative.name,
    component: representative.name,
    path: representative.path,
    source: `../../lib/${representative.path}`,
  };

  if (platform !== 'react-native') {
    return entry;
  }

  return {
    ...entry,
    themed,
    light: themed ? { name: light.name, path: light.path } : null,
    dark: themed ? { name: dark.name, path: dark.path } : null,
  };
}

/**
 * All assets share one Code Connect template per platform — batch files
 * pair that single template with a JSON list of per-component-set data,
 * rather than one file per asset.
 */
function generateBatchFiles(platform, groups) {
  const templateDir = path.resolve(__dirname, '..', 'templates', platform);
  const outputDir = path.resolve(__dirname, '..', 'figma-code-connect', platform);

  fs.copySync(
    path.join(templateDir, 'assets.figma.batch.ts'),
    path.join(outputDir, 'assets.figma.batch.ts')
  );

  const components = groups.map(members =>
    buildEntry(platform, members[0].componentSetId, members)
  );

  fs.outputFileSync(
    path.join(outputDir, 'assets.figma.batch.json'),
    JSON.stringify({ templateFile: './assets.figma.batch.ts', components }, null, 2) + '\n',
    { encoding: 'utf8' }
  );
}

async function main() {
  const { platform } = parseArgs(process.argv.slice(2));
  const groups = groupByComponentSet(getAssets());
  generateBatchFiles(platform, groups);
}

main()
  .then(() => {
    console.log('Thanks, see ya 👋');
  })
  .catch(err => {
    console.error(err);
    process.exit(1);
  });
